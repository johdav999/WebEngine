"""Run with Blender --background --factory-startup --python-exit-code 1 --python this.py."""
import importlib.util
from pathlib import Path
import tempfile
import bpy

root = Path(__file__).resolve().parents[1]
spec = importlib.util.spec_from_file_location('webengine_cloth', root / 'tools/blender-cloth/export_cloth.py')
exporter = importlib.util.module_from_spec(spec)
spec.loader.exec_module(exporter)
bpy.ops.wm.read_factory_settings(use_empty=True)
arm = bpy.data.armatures.new('Rig')
rig = bpy.data.objects.new('Rig', arm)
bpy.context.collection.objects.link(rig)
bpy.context.view_layer.objects.active = rig
rig.select_set(True)
bpy.ops.object.mode_set(mode='EDIT')
bone = arm.edit_bones.new('Root')
bone.head = (0, 0, 0)
bone.tail = (0, 0, 1)
child = arm.edit_bones.new('Tip')
child.head = (0, 0, 1)
child.tail = (0, 0, 2)
child.parent = bone
child.roll = .3
bpy.ops.object.mode_set(mode='OBJECT')
mesh = bpy.data.meshes.new('Cape')
mesh.from_pydata([(-.5, -.1, 1), (.5, -.1, 1), (-.5, -.1, 0), (.5, -.1, 0)], [], [(0, 2, 1), (1, 2, 3)])
mesh.update()
obj = bpy.data.objects.new('Cape', mesh)
bpy.context.collection.objects.link(obj)
obj.vertex_groups.new(name='Root').add([0, 1, 2, 3], 1, 'REPLACE')
obj.vertex_groups.new(name='WE_Pin').add([0, 1], 1, 'REPLACE')
obj.vertex_groups.new(name='WE_InvMass').add([2, 3], 1, 'REPLACE')
mod = obj.modifiers.new('Armature', 'ARMATURE')
mod.object = rig
bpy.context.view_layer.update()
obj.parent = rig
obj.matrix_world = rig.matrix_world.copy()
obj.vertex_groups['Root'].add([2, 3], .5, 'REPLACE')
obj.vertex_groups.new(name='Tip').add([2, 3], .5, 'REPLACE')
uv = mesh.uv_layers.new()
for loop in mesh.loops:
    uv.data[loop.index].uv = (mesh.vertices[loop.vertex_index].co.x + .5, mesh.vertices[loop.vertex_index].co.z)
bpy.context.view_layer.objects.active = obj
obj.select_set(True)
with tempfile.TemporaryDirectory() as directory:
    path = Path(directory) / 'cape.wecloth'
    result = exporter.export_cloth(obj, path)
    valid = path.read_bytes()
    assert result == dict(vertices=4, triangles=2, links=6, pins=2), result
    assert exporter.export_cloth(obj, None) == result
    assert exporter.export_cloth(obj, path) == result and path.read_bytes() == valid
    # Export failure must preserve existing bytes; test real authoring errors.
    def rejects():
        try:
            exporter.export_cloth(obj, path)
        except ValueError:
            assert path.read_bytes() == valid
        else:
            raise AssertionError('Invalid garment accepted')
    mod.use_deform_preserve_volume = True
    rejects()
    mod.use_deform_preserve_volume = False
    rig.location.x = .25
    rejects()
    rig.location.x = 0
    bpy.context.view_layer.update()
    obj.vertex_groups['WE_Pin'].remove([0, 1])
    rejects()
    obj.vertex_groups['WE_Pin'].add([0, 1], 1, 'REPLACE')
    saved_uv = uv.data[3].uv.copy()
    uv.data[3].uv = (.123, .456)
    rejects()
    uv.data[3].uv = saved_uv
    saved_uv = uv.data[5].uv.copy()
    uv.data[5].uv = (0, 1)
    rejects()
    uv.data[5].uv = saved_uv
    exporter.register()
    exporter.unregister()
    glb = Path(directory) / 'driver.glb'
    bpy.ops.export_scene.gltf(filepath=str(glb), export_format='GLB', use_selection=True, export_animations=False)
    def array(name, data):
        return 'inline constexpr unsigned char ' + name + '[] = {\n' + '\n'.join(
            ','.join(str(v) for v in data[i:i+32]) + ',' for i in range(0, len(data), 32)) + '\n};\n'
    (root / 'tests/cloth_asset_fixture.hpp').write_text(
        '// Generated by tests/blender_cloth_fixture.py using Blender; do not hand-edit.\n#pragma once\n' +
        array('clothAssetFixture', valid) + array('clothDriverFixture', glb.read_bytes()), encoding='utf-8')
print('Blender cloth exporter PASS: deterministic export, pins/masses, invalid inputs, atomic output, add-on registration')
