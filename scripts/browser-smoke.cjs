function differentPixels(a, b) {
  const pa = PNG.sync.read(a), pb = PNG.sync.read(b);
  assert.equal(pa.width, pb.width); assert.equal(pa.height, pb.height);
  let changed = 0;
  for (let i = 0; i < pa.data.length; i += 4) {
    if (Math.abs(pa.data[i] - pb.data[i]) + Math.abs(pa.data[i+1] - pb.data[i+1]) + Math.abs(pa.data[i+2] - pb.data[i+2]) > 15) changed++;
  }
  return changed;
}
